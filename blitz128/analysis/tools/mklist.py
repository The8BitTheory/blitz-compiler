import pickle,sys,os
sys.path.insert(0,'.')
from rtdis import *
la,m=load(); base=la
code,ent=pickle.load(open('/tmp/rt.pkl','rb'))
lo,hi=0x1c01,0x46b0
labels=set(ent)
for a,v in code.items():
    if v[2] is not None and lo<=v[2]<hi and v[3] in('JSR','JMP','BCC','BCS','BEQ','BNE','BMI','BPL','BVC','BVS'): labels.add(v[2])
SYS={0xff00:'MMU_CR',0xff01:'MMU_LCRA',0xff02:'MMU_LCRB',0xff03:'MMU_LCRC',0xff04:'MMU_LCRD',0xffd2:'CHROUT',0xffe4:'GETIN',0xffcf:'CHRIN',0xffc3:'CLOSE',
     0xffc0:'OPEN',0xffc9:'CHKOUT',0xffc6:'CHKIN',0xffcc:'CLRCHN',0xffbd:'SETNAM',0xffba:'SETLFS',0xffd5:'LOAD',0xffd8:'SAVE',0xffb7:'READST',0xff81:'CINT',0xff84:'IOINIT',0xffe1:'STOP',0xfff0:'PLOT'}
def lbl(a): return ('L%04x'%a)
out=[]
a=lo
out.append('; Blitz!128 runtime AS EXECUTED (patcher block $23D0-$2437 decrypted, keys patched; built by runimg.py), load $%04x'%la)
out.append('; auto-generated by tools/mklist.py - recursive-descent; data shown as .byte')
out.append('')
while a<hi:
    if a in labels: out.append('%s:'%lbl(a))
    if a in code:
        n,t,tg,mn,mo,v=code[a]
        txt=t
        if tg is not None and tg in SYS: txt=txt.replace('$%04x'%tg,SYS[tg])
        elif tg is not None and tg in labels and mn in('JSR','JMP','BCC','BCS','BEQ','BNE','BMI','BPL','BVC','BVS'): txt=txt.replace('$%04x'%tg,lbl(tg))
        out.append('  %04x  %-9s  %s'%(a,m[a-base:a+n-base].hex(),txt)); a+=n
    else:
        e=a+1
        while e<hi and e not in code and e not in labels and e-a<16: e+=1
        out.append('  %04x  .byte %s'%(a,','.join('$%02x'%x for x in m[a-base:e-base]))); a=e
open(os.environ.get('RTOUT','../runtime_1c01.asm'),'w').write('\n'.join(out)+'\n')
print(len(out))
