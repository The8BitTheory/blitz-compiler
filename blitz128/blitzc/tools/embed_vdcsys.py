#!/usr/bin/env python3
"""Write js/vdcsysimg.js: VDCSYS (vdcsys/vdcsys.s, assembled with cl65) as a byte array for the vdc2sys option.
VDCSYS is the SYS/USR library for programs converted by js/vdc2sys.js; it needs VDC-BASIC v3 (vdcbasic3.bin at $1C00).
The source comes from the vdc-basic repository (examples/vertrot/vdcsys.s)."""
import hashlib, os, subprocess, tempfile
H = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(H, '..', 'vdcsys')
with tempfile.TemporaryDirectory() as t:
    out = os.path.join(t, 'vdcsys.prg')
    subprocess.run(['cl65', '-t', 'none', '-C', os.path.join(D, 'vdcsys.cfg'), '-o', out, os.path.join(D, 'vdcsys.s')], check=True)
    obj = os.path.join(D, 'vdcsys.o')
    if os.path.exists(obj):
        os.remove(obj)
    b = open(out, 'rb').read()
rows = '\n'.join('  ' + ', '.join(str(x) for x in b[i:i + 24]) + ',' for i in range(0, len(b), 24))
open(os.path.join(H, '..', 'js', 'vdcsysimg.js'), 'w').write(
    '// GENERATED by tools/embed_vdcsys.py from vdcsys/vdcsys.s: VDCSYS (load address $1300), %d bytes, sha1 %s\n'
    'export const VDCSYS = Uint8Array.from([\n%s\n]);\n' % (len(b), hashlib.sha1(b).hexdigest(), rows))
print('js/vdcsysimg.js', len(b), 'bytes')
