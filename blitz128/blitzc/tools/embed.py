#!/usr/bin/env python3
"""Write js/blitzimg.js: the FIXED BLITZ!.128 (fixed/blitz!.128.prg, made by tools/patch_blitz128.py from Skyles V860929)
as base64, so the port needs no extra input file."""
import base64, os, hashlib
H = os.path.dirname(os.path.abspath(__file__))
b = open(os.path.join(H, '..', '..', 'fixed', 'blitz!.128.prg'), 'rb').read()
s = base64.b64encode(b).decode()
lines = '\n'.join(repr(s[i:i + 100]) + ' +' for i in range(0, len(s), 100))[:-2]
o = open(os.path.join(H, '..', '..', 'blitz!.128.prg'), 'rb').read()
so = base64.b64encode(o).decode()
olines = '\n'.join(repr(so[i:i + 100]) + ' +' for i in range(0, len(so), 100))[:-2]
open(os.path.join(H, '..', 'js', 'blitzimg.js'), 'w').write(
    '// GENERATED by tools/embed.py: BLITZ!.128 fixed (Skyles V860929 + fix, see tools/patch_blitz128.py), %d bytes, sha1 %s\n'
    '// Source of the runtime images of the Improved 2026 runtime.\n'
    'export const BLITZ_B64 =\n%s;\n'
    '// The untouched BLITZ!.128 of this repository (Skyles V860929, 1986, with its defects), %d bytes, sha1 %s\n'
    '// Source of the runtime images of the "Original runtime" (compiler and runtime exactly as in 1986).\n'
    'export const BLITZ_ORIG_B64 =\n%s;\n' % (len(b), hashlib.sha1(b).hexdigest(), lines.replace("'", '"'),
                                           len(o), hashlib.sha1(o).hexdigest(), olines.replace("'", '"')))
print('js/blitzimg.js', len(b), 'bytes')
