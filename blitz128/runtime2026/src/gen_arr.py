#!/usr/bin/env python3
"""Generate perf/proto/fastarr.s (prototype P2) from analysis/runtime/runtime.s.

P2 = the array element address calculation `var_long_ref2` copied into the shared top page ($FC00) with every bank-1 read
done inline (`STA $FF02 / LDA (zp),Y / STA $FF01`, 13 cycles) instead of `JSR rd_zp` / `JSR rd_zp_set` (25/29 cycles).
The first read uses the zero-page pointer passed in A (self-modified operand, $31 from var_long_ref, $6A from POINTER);
after `lda #$61 : jsr rd_zp_set` all reads go through ($61).  The element is then loaded/stored by the P1 fast entries.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'fastarr.s')
src = open(os.path.join(HERE, '..', '..', 'analysis', 'runtime', 'runtime.s')).read().split('\n')
a = src.index('var_long_ref2:')
b = src.index('str_store:')
body = [l for l in src[a + 1:b] if not l.startswith(';')]

FAST = {'var_store_float', 'var_load_float', 'var_load_int', 'var_store_int', 'var_load_str'}
out = []
zp = 'dyn'            # pointer of the current rd_zp
ndyn = 0
i = 0
while i < len(body):
    l = body[i]
    s = l.strip()
    l = re.sub(r'var_long_ref2_', 'fa_', l)
    if s == 'jsr  rd_zp_set':
        prev = out[-1].strip() if out else ''
        if prev.startswith('lda  #$'):
            zp = prev.split('#')[1]
            out.pop()
            out += ['        sta  MMU_LCRB', '        lda  (%s),y' % zp, '        sta  MMU_LCRA']
        else:                       # first read: pointer in A
            out += ['        sta  fa_dyn1+1', '        sta  fa_dyn2+1', '        sta  fa_dyn3+1',
                    '        sta  MMU_LCRB', 'fa_dyn1: lda  ($00),y', '        sta  MMU_LCRA']
            zp, ndyn = 'dyn', 1
    elif s == 'jsr  rd_zp':
        if zp == 'dyn':
            ndyn += 1
            out += ['        sta  MMU_LCRB', 'fa_dyn%d: lda  ($00),y' % ndyn, '        sta  MMU_LCRA']
        else:
            out += ['        sta  MMU_LCRB', '        lda  (%s),y' % zp, '        sta  MMU_LCRA']
    else:
        m = re.match(r'\s+(jmp|bvs|bvc)\s+(\w+)$', l)
        if m and m.group(2) in FAST:
            l = l.replace(m.group(2), 'fast_' + m.group(2))
        elif m and m.group(2) == 'str_store':
            l = l.replace('str_store', 'fa_str_store')
        out.append(l)
    i += 1
assert ndyn == 3, ndyn

hdr = '''; fastarr.s -- GENERATED by gen_fastarr.py from analysis/runtime/runtime.s (var_long_ref2), do not edit.
; Prototype P2: array element addressing in the shared top page with inline bank-1 reads.  Needs fastvar.s (P1).
        .setcpu "6502"
        .include "rtsyms.inc"
        .import fast_var_store_float, fast_var_load_float, fast_var_load_int, fast_var_store_int, fast_var_load_str
        .segment "EXT"
        .export stub_var_long_ref2
stub_var_long_ref2:
        sta  MMU_LCRA              ; see fastvar.s: the caller may have left CR=$02 (KERNAL ROM over $FC00)
        jmp  fast_var_long_ref2
        .segment "SHARED"
fast_var_long_ref2:'''
tail = ['fa_str_store:', '        jmp  str_store', '']
open(OUT, 'w').write(hdr + '\n' + '\n'.join(out) + '\n' + '\n'.join(tail))

