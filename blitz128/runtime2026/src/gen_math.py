#!/usr/bin/env python3
"""Generate build/mathcopy.s: RAM copies of the C128 BASIC ROM routines SQR/^ (FPWR), LOG, EXP (+POLYX/POLY), COS/SIN/TAN, ATN
for the FASTMATH variant of the Improved 2026 runtime.

Why copies: these ROM routines call FMULT ($8A08/$8A24/$8A27) many times (polynomials).  In the ROM those calls cannot be redirected,
in a RAM copy they go to fast_fmultt (math.s).  The copies run in MMU configuration A (all RAM); everything else they call in the ROM
goes through a thunk r_XXXX -> rom_call ($0287, common RAM: STA $FF03 / JSR XXXX / STA $FF01), which preserves A, X, Y and the flags.
Special cases:
  * MULDIV $8AEE/$8B09 does `PLA PLA` (returns 0 from its caller, here EXP) - RAM versions m_8AEE/m_8B09 in math.s (through a thunk
    the PLA PLA would remove the trampoline frame and the RTS would return into the copy with the ROM switched in).
    Every other thunk target was checked for PLA/PLP/TSX/TXS on its own stack level: none unbalanced.
  * POLY reads the coefficient count with `lda ($72),y` from the ROM table: poly_read emulates it from copies of the tables.
  * LOG ends by falling into $8A08 (FMULT with memory operand): `jmp fm_mult_mem`.
The byte sequence of every copy is the ROM's; only operands of JSR/JMP/branches and the special cases differ.
usage: gen_math.py <out.s>
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'blitzc', 'tools'))
from dis6502 import decode

ROMDIR = os.environ.get('C128ROMS', os.path.expanduser('~/.local/share/vice/C128'))
LO = open(os.path.join(ROMDIR, 'basiclo-318018-04.bin'), 'rb').read()
HI = open(os.path.join(ROMDIR, 'basichi-318019-04.bin'), 'rb').read()
rom = lambda a: LO[a - 0x4000] if a < 0x8000 else HI[a - 0x8000]

# (start, end) of copied code; end = first address behind the routine
RANGES = [(0x89ca, 0x8a08),     # LOG (falls into $8A08)
          (0x8fb7, 0x9005),     # SQR, FPWR ($8FC1), negate ($8FFA)
          (0x9033, 0x90d0),     # EXP, POLYX ($9086), POLY ($909C/$90A0)
          (0x9409, 0x9485),     # COS, SIN ($9410), TAN ($9459)
          (0x94b3, 0x94e3)]     # ATN
FALL = {0x8a08: 'fm_mult_mem'}  # fall-through at a range end
FMULT = {0x8a08: 'fm_mult_mem', 0x8a24: 'fm_mult_bank', 0x8a27: 'fast_fmultt'}
SPECIAL = {0x8aee: 'm_8AEE', 0x8b09: 'm_8B09'}
POLY_TABLES = [0x89a1, 0x900a, 0x9494, 0x94e3]   # coefficient tables read by POLY (count byte + 5 bytes per coefficient)


def main(out):
    ins = []                                    # (addr, size, mnemonic, mode, operand, text, target)
    for a, b in RANGES:
        pc = a
        while pc < b:
            n, mn, m, op, t, tg = decode(HI, pc, 0x8000)
            assert mn != '.byte', 'data inside a copied range at $%04X' % pc
            ins.append((pc, n, mn, m, op, t, tg))
            pc += n
        assert pc == b, 'range $%04X-$%04X does not end on an instruction boundary' % (a, b)
    copied = {i[0] for i in ins}
    thunks = set()
    L = ['; mathcopy.s -- GENERATED by runtime2026/src/gen_math.py from the C128 BASIC ROM (318018-04/318019-04), do not edit.',
         '        .setcpu "6502"', '        .include "rtsyms.inc"',
         '        .import fast_fmultt, fm_mult_mem, fm_mult_bank, m_8B09, m_8AEE',
         '        .export m_89CA, m_8FB7, m_8FC1, m_9033, m_9409, m_9410, m_9459, m_94B3',
         '        .segment "EXT"']
    ends = {b for a, b in RANGES}
    for (pc, n, mn, m, op, t, tg) in ins:
        lab = 'm_%04X:' % pc
        if m == 'rel':
            assert tg in copied, 'branch out of the copies at $%04X' % pc
            code = '%s m_%04X' % (mn.lower(), tg)
        elif mn in ('JSR', 'JMP') and m == 'abs':
            if tg in copied: dst = 'm_%04X' % tg
            elif tg in FMULT: dst = FMULT[tg]
            elif tg in SPECIAL: dst = SPECIAL[tg]
            else:
                dst = 'r_%04X' % tg; thunks.add(tg)
            code = '%s %s' % (mn.lower(), dst)
        elif mn == 'LDA' and m == 'izy' and op == 0x72:
            code = 'jsr poly_read                ; lda ($72),y from the ROM table'
        else:
            assert m not in ('ind', 'izx', 'izy') or op < 0x80, 'indirect access at $%04X: %s' % (pc, t)
            if m in ('abs', 'abx', 'aby'):
                assert op < 0x4000 or 0xd000 <= op < 0xe000, 'absolute ROM access at $%04X: %s' % (pc, t)
            code = '.byte ' + ','.join('$%02x' % rom(pc + k) for k in range(n)) + '          ; ' + t.lower()
        L.append('%-9s%s' % (lab, code))
        if pc + n in ends and pc + n in FALL:
            L.append('         jmp %s           ; falls into $%04X in the ROM' % (FALL[pc + n], pc + n))
    L.append('; ---- thunks: call a ROM routine through rom_call (A, X, Y and flags preserved)')
    for t in sorted(thunks):
        L.append('r_%04X:  php' % t)
        L += ['         pha', '         lda #<$%04X' % t, '         sta rom_call_lo', '         lda #>$%04X' % t,
              '         sta rom_call_hi', '         pla', '         plp', '         jmp rom_call']
    # POLY tables: copies of the bytes POLY reads with lda ($72),y (the count byte)
    L.append('; ---- POLY: lda ($72),y for the coefficient tables (copies of the count bytes)')
    L += ['poly_read:', '         php', '         stx  pr_x', '         tya', '         clc', '         adc  $72', '         sta  pr_pl',
          '         lda  #0', '         adc  $73', '         sta  pr_ph', '         ldx  #%d' % (len(POLY_TABLES) - 1),
          '@l:      lda  pr_pl', '         cmp  pr_lo,x', '         bne  @n', '         lda  pr_ph', '         cmp  pr_hi,x', '         beq  @f',
          '@n:      dex', '         bpl  @l', '         brk                          ; not one of the known tables (cannot happen)',
          '@f:      lda  pr_val,x', '         ldx  pr_x', '         plp', '         ora  #0                       ; flags as LDA',
          '         rts', 'pr_x:    .byte 0', 'pr_pl:   .byte 0', 'pr_ph:   .byte 0']
    L.append('pr_lo:   .byte ' + ','.join('$%02x' % (t & 255) for t in POLY_TABLES))
    L.append('pr_hi:   .byte ' + ','.join('$%02x' % (t >> 8) for t in POLY_TABLES))
    L.append('pr_val:  .byte ' + ','.join('$%02x' % rom(t) for t in POLY_TABLES))
    open(out, 'w').write('\n'.join(L) + '\n')
    print('mathcopy.s: %d instructions copied, %d ROM thunks' % (len(ins), len(thunks)))


if __name__ == '__main__':
    main(sys.argv[1])
