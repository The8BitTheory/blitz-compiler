#!/usr/bin/env python3
"""runtime2026/build.py -- build the "Improved 2026 runtime" for the JavaScript compiler.

The original runtime images stay in place byte for byte (image 1 $1C01-$46AF, image 2 $4001-$6C40, as in fixed/blitz!.128.prg
V261123).  The improvements live in an extension block assembled directly behind each image (src/*.s, ld65 config ext.cfg) and are
reached through a few patched entry points:
    init: `jsr install_trampolines`           -> `jsr hook_init`
    <label> (first 3 bytes)                   -> `jmp stub_<label>`     (stub: STA $FF01, then the code in the shared top page)
    NEXT's FADD call site                     -> `jsr fast_next_add : jmp <behind>`
    FASTMATH: float_arith_rom `jsr rom_call_x` -> `jsr fm_op`;  rom_function `jmp rom_ax_tail` -> `jmp fm_func`
The compiler writes runtime image + extension (T1% / TE% come from the runtime choice, see js/rt.js) and puts header and bytecode
behind it.  Variants: plain and FASTMATH (fast multiplication + RAM copies of SQR/LOG/EXP/SIN/COS/TAN/ATN/^).

Output: build/ (objects, labels) and ../blitzc/js/rt2026img.js (base64 data for the port).
usage: build.py [--check]     (--check: build only, do not write rt2026img.js)
"""
import base64, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RTDIR = os.path.join(HERE, '..', 'analysis', 'runtime')
BUILD = os.path.join(HERE, 'build')
JSOUT = os.path.join(HERE, '..', 'blitzc', 'js', 'rt2026img.js')
BLITZ = os.path.join(HERE, '..', 'fixed', 'blitz!.128.prg')

IMAGES = {
    1: dict(src='runtime.s', cfg='rt.cfg', base=0x1c01, ext=0x46b0, run=os.path.join(RTDIR, '..', 'run_1c01.bin')),
    2: dict(src='runtime2.s', cfg='rt2.cfg', base=0x4001, ext=0x6c41, run=os.path.join(RTDIR, 'run_4001_fixed.bin')),
}
SOURCES = ['var.s', 'arr.s', 'next.s']          # arr.s is generated by src/gen_arr.py
MATH = ['math.s', 'mathcopy.s']                 # FASTMATH only (mathcopy.s is generated by src/gen_math.py)


def sh(*a):
    subprocess.check_call(list(a))


def symbols(img):
    """rtsyms<img>.inc: every label and equate of runtime.s / runtime2.s (same names, different addresses)."""
    I = IMAGES[img]
    o, lbl = os.path.join(BUILD, 'rt%d.o' % img), os.path.join(BUILD, 'rt%d.lbl' % img)
    sh('ca65', '-g', '-o', o, os.path.join(RTDIR, I['src']))
    sh('ld65', '-C', os.path.join(RTDIR, I['cfg']), '-Ln', lbl, '-o', os.path.join(BUILD, 'rt%d.bin' % img), o)
    syms = {}
    for line in open(os.path.join(RTDIR, I['src'])):
        m = re.match(r'^([a-zA-Z_][a-zA-Z0-9_]*)\s*=\s*\$([0-9a-fA-F]+)', line)
        if m: syms[m.group(1)] = int(m.group(2), 16)
    for line in open(lbl):
        _, a, n = line.split()
        syms[n.lstrip('.')] = int(a, 16)
    with open(os.path.join(BUILD, 'rtsyms%d.inc' % img), 'w') as f:
        for n, a in sorted(syms.items()): f.write('%s = $%04X\n' % (n, a))
    return syms


def find(img_bytes, base, pat, what):
    i = img_bytes.find(pat)
    assert i >= 0 and img_bytes.find(pat, i + 1) < 0, 'pattern for %s not unique' % what
    return base + i


def build(img, fastmath, syms):
    I = IMAGES[img]
    run = open(I['run'], 'rb').read()[2:]
    tag = '%d%s' % (img, 'm' if fastmath else '')
    objs = []
    srcs = SOURCES + (MATH if fastmath else [])
    for s in srcs:
        o = os.path.join(BUILD, '%s_%s.o' % (s[:-2], tag))
        p = os.path.join(BUILD, s) if s in ('arr.s', 'mathcopy.s') else os.path.join(HERE, 'src', s)
        args = ['ca65', '-I', BUILD, '-I', os.path.join(HERE, 'src'), '-D', 'IMG=%d' % img, '-o', o, p]
        if fastmath: args[1:1] = ['-D', 'FASTMATH=1']
        sh(*args)
        objs.append(o)
    binf, lbl = os.path.join(BUILD, 'ext%s.bin' % tag), os.path.join(BUILD, 'ext%s.lbl' % tag)
    sh('ld65', '-C', os.path.join(HERE, 'ext.cfg'), '-D', '__EXT__=$%04X' % I['ext'], '-Ln', lbl,
       '-m', os.path.join(BUILD, 'ext%s.map' % tag), '-o', binf, *objs)
    ext = open(binf, 'rb').read()
    ex = {}
    for line in open(lbl):
        _, a, n = line.split()
        ex[n.lstrip('.')] = int(a, 16)
    assert ex['__SHARED_SIZE__'] <= 0x300, 'shared page too big: %d bytes' % ex['__SHARED_SIZE__']
    assert I['ext'] + len(ext) <= 0x8000, 'extension must end below $8000 (visible with MMU CR=$02)'

    patches = []

    def patch(addr, new, old):
        i = addr - I['base']
        assert not (img == 1 and 0x23d0 <= addr < 0x2438), 'inside the encrypted patcher block'
        assert run[i:i + len(old)] == bytes(old), 'image %d: unexpected bytes at $%04X: %s' % (img, addr, run[i:i + 4].hex())
        patches.append([addr, list(new)])

    w = lambda a: [a & 255, a >> 8]
    it = syms['install_trampolines']
    patch(syms['init'] + 12, [0x20] + w(ex['hook_init']), [0x20] + w(it))
    for n, a in ex.items():
        if n.startswith('stub_') and n[5:] in syms and not n.startswith('stub_next_'):
            site = syms[n[5:]]
            patch(site, [0x4c] + w(a), run[site - I['base']:site - I['base'] + 3])
    # NEXT: lda #$48 / sta rom_call_lo / ldx #$88 / lda fac_exp / jsr rom_call_x / jsr round_fac   (15 bytes)
    rcx, rf = syms['rom_call_x'], syms['round_fac']
    pat = bytes([0xa9, 0x48, 0x8d, 0x8b, 0x02, 0xa2, 0x88, 0xa5, 0x63, 0x20] + w(rcx) + [0x20] + w(rf))
    site = find(run, I['base'], pat, 'NEXT FADD')
    patch(site, [0x20] + w(ex['fast_next_add']) + [0x4c] + w(site + 15), pat[:6])
    # NEXT: the four ld_var/st_var calls (float path in op13_NEXT_chk, integer path next_step_add) -> unrolled copies
    lv, sv = syms['ld_var'], syms['st_var']
    lo, hi = syms['op13_NEXT_chk'], syms['next_step_add'] + 0x60
    for pre, tgt, stub in (([0xa0, 0x04, 0xa2, 0x0b], lv, 'stub_next_ld5'), ([0xa2, 0x04, 0xa0, 0x04], sv, 'stub_next_st5'),
                           ([0xc8, 0xa2, 0x01], lv, 'stub_next_ld2'), ([0xa2, 0x01, 0xa0, 0x01], sv, 'stub_next_st2')):
        pat = bytes(pre + [0x20] + w(tgt))
        i = run.find(pat, lo - I['base'], hi - I['base'])
        assert i >= 0 and run.find(pat, i + 1, hi - I['base']) < 0, 'NEXT call site ' + stub
        patch(I['base'] + i + len(pre), [0x20] + w(ex[stub]), [0x20] + w(tgt))
    if fastmath:
        # float_arith_rom: ... lda fac_exp / jsr rom_call_x / jmp next_inc1_y0
        fa = syms['float_arith_rom']
        i = run.find(bytes([0xa5, 0x63, 0x20] + w(rcx)), fa - I['base'])
        assert 0 < i - (fa - I['base']) < 20
        patch(I['base'] + i + 2, [0x20] + w(ex['fm_op']), [0x20] + w(rcx))
        # rom_function: ... lda #$44 / ldx #$4c / jmp rom_ax_tail
        rfn, rat = syms['rom_function'], syms['rom_ax_tail']
        i = run.find(bytes([0xa9, 0x44, 0xa2, 0x4c, 0x4c] + w(rat)), rfn - I['base'])
        assert 0 < i - (rfn - I['base']) < 40
        patch(I['base'] + i + 4, [0x4c] + w(ex['fm_func']), [0x4c] + w(rat))
    return dict(ext=base64.b64encode(ext).decode(), extAt=I['ext'], patches=patches,
                end=I['ext'] + len(ext), shared=ex['__SHARED_SIZE__'], labels={k: v for k, v in ex.items() if not k.startswith('__')})


def main():
    os.makedirs(BUILD, exist_ok=True)
    sh(sys.executable, os.path.join(HERE, 'src', 'gen_arr.py'), os.path.join(BUILD, 'arr.s'))
    sh(sys.executable, os.path.join(HERE, 'src', 'gen_math.py'), os.path.join(BUILD, 'mathcopy.s'))
    syms = {img: symbols(img) for img in IMAGES}
    out = {}
    for fm in (False, True):
        if fm and not os.path.exists(os.path.join(HERE, 'src', MATH[0])): continue
        v = {}
        for img in IMAGES:
            # the sources include "rtsyms.inc": the symbols of the image being built
            with open(os.path.join(BUILD, 'rtsyms%d.inc' % img)) as a, open(os.path.join(BUILD, 'rtsyms.inc'), 'w') as b: b.write(a.read())
            v[img] = build(img, fm, syms[img])
        out['fastmath' if fm else 'plain'] = v
    for k, v in out.items():
        for img, d in v.items():
            print('%-8s image %d: extension $%04X-$%04X (%d bytes, %d in the shared page), %d patches'
                  % (k, img, d['extAt'], d['end'] - 1, d['end'] - d['extAt'], d['shared'], len(d['patches'])))
    if '--check' in sys.argv: return
    js = json.dumps(out, separators=(',', ':'))
    open(JSOUT, 'w').write('// GENERATED by runtime2026/build.py: Improved 2026 runtime (extension blocks + patches), do not edit.\n'
                           'export const RT2026 = %s;\n' % js)
    print('wrote', JSOUT)


if __name__ == '__main__':
    main()
