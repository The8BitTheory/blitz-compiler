EXTLEN={0x14:4,0x15:4}
CONST={0xa9:'EL',0xaa:'X?AA',0xab:'ST',0xac:'TI',0xad:'DS',0xae:'DS$',0xaf:'TI$'}
def decode(bs,i):
    b=bs[i]
    if b==0: x=bs[i+1]; return EXTLEN.get(x,2),'X%02x'%x,bs[i+2:i+EXTLEN.get(x,2)]
    if b<0x0e: return 1,BIN[b],()
    if b<0x80:
        if b in SPECIAL:
            if b==0x37: n=bs[i+5]; return 6,'DEFFN',(bs[i+1]|bs[i+2]<<8,bs[i+3]|bs[i+4]<<8,n)
            n=bs[i+1]; return n,MAIN[b],tuple(bs[i+2:i+n])
        n=LEN.get(b,1); return n,MAIN.get(b,'OP%02x'%b),tuple(bs[i+1:i+n])
    if b<0xa0: return 1,'LD',(b-0x80,)
    if b<0xa4: return 2,'LDL',((b&3)<<8|bs[i+1],)
    if b==0xa4: return 2,'LDA()',(bs[i+1],)
    if b==0xa5: return 3,'LDA()L',(bs[i+1],bs[i+2])
    if b==0xa6: return 2,'#',(bs[i+1],)
    if b==0xa7: return 3,'#',(bs[i+1]<<8|bs[i+2],)
    if b==0xa8: return 6,'#F',tuple(bs[i+1:i+6])
    if b<0xb0: return 1,CONST.get(b,'C%02x'%b),()
    if b<0xc0: return 1,'#',(b-0xb0,)
    if b<0xe0: return 1,'ST',(b-0xc0,)
    if b<0xe4: return 2,'STL',((b&3)<<8|bs[i+1],)
    if b==0xe4: return 2,'STA()',(bs[i+1],)
    if b==0xe5: return 3,'STA()L',(bs[i+1],bs[i+2])
    if b==0xe6: return 1,'ER',()
    if b==0xe7: return 2+bs[i+1],'$',(bs[i+1],)
    if b<0xf0: return 1+(b-0xe8),'$',(b-0xe8,)
    return 1,'#',(b-0xe0,)
